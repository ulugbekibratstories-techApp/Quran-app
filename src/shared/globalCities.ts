// City search function across all languages
export function searchGlobalCities(query: string): GlobalCity[] {
  const q = query.trim().toLowerCase();
  if (!q) return GLOBAL_CITIES;

  return GLOBAL_CITIES.filter((city) => {
    return (
      city.id.toLowerCase().includes(q) ||
      city.nameLatin.toLowerCase().includes(q) ||
      city.nameCyrillic.toLowerCase().includes(q) ||
      city.nameEnglish.toLowerCase().includes(q) ||
      city.nameRussian.toLowerCase().includes(q) ||
      city.nameArabic.includes(q) ||
      city.countryLatin.toLowerCase().includes(q) ||
      city.countryCyrillic.toLowerCase().includes(q) ||
      city.countryCode.toLowerCase() === q ||
      city.region.toLowerCase().includes(q)
    );
  });
}

export function getCityById(id: string): GlobalCity {
  return GLOBAL_CITIES.find((c) => c.id === id) || GLOBAL_CITIES[0];
}
